const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { createApp, addDays, rebalance } = require('./index.cjs');

test('recurrence handles month and year boundaries', () => {
  assert.equal(addDays('2026-12-31', 1), '2027-01-01');
  assert.equal(addDays('2028-02-28', 1), '2028-02-29');
});
test('automatic balancing considers repeat frequency and effort', () => {
  const house = { members: [{ id: 'a' }, { id: 'b' }], chores: [{ id: '1', frequencyDays: 1, effort: 3 }, { id: '2', frequencyDays: 7, effort: 3 }, { id: '3', frequencyDays: 7, effort: 2 }] };
  rebalance(house);
  assert.equal(house.chores[0].memberId, 'a');
  assert.equal(house.chores[1].memberId, 'b');
  assert.equal(house.chores[2].memberId, 'b');
});
test('accounts, invitations, isolation, shared chores, groceries, and disk persistence', async t => {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), 'roomies-api-test-'));
  const dataFile = path.join(folder, 'data.json');
  let server = createApp({ dataFile, buildDir: folder });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  let origin = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { await new Promise(resolve => server.close(resolve)); fs.rmSync(folder, { recursive: true, force: true }); });
  const call = async (route, method = 'GET', data, cookie, extraHeaders = {}) => {
    const response = await fetch(`${origin}/api${route}`, { method, headers: { ...(method !== 'GET' ? { 'Content-Type': 'application/json' } : {}), ...(cookie ? { Cookie: cookie } : {}), ...extraHeaders }, ...(data === undefined ? {} : { body: JSON.stringify(data) }) });
    return { status: response.status, body: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0], fullCookie: response.headers.get('set-cookie') };
  };
  const alice = await call('/auth/signup', 'POST', { name: 'Alice', email: 'alice@example.com', password: 'test-password-123' });
  assert.equal(alice.status, 201);
  assert.match(alice.fullCookie, /HttpOnly/);
  assert.match(alice.fullCookie, /SameSite=Lax/);
  assert.equal(alice.body.user.passwordHash, undefined);
  assert.equal((await call('/auth/login', 'POST', { email: 'alice@example.com', password: 'wrong-password' })).status, 401);
  assert.equal((await call('/household')).status, 401);
  const payload = { name: 'Test Pink House', type: 'apartment', living: 'sharing', features: ['chores', 'groceries'], areas: ['Kitchen', 'Bathroom'], members: [{ id: 'alice-slot', name: 'Alice' }, { id: 'bob-slot', name: 'Bob' }], chores: [{ id: 'c1', name: 'Dishes', area: 'Kitchen', frequencyDays: 1, effort: 1 }, { id: 'c2', name: 'Clean shower', area: 'Bathroom', frequencyDays: 7, effort: 3 }], rotate: true, assignmentMode: 'auto' };
  const created = await call('/households', 'POST', payload, alice.cookie);
  assert.equal(created.status, 201);
  const code = created.body.house.inviteCode;
  assert.equal(code.length, 12);
  assert.equal((await call(`/invites/${code}`)).body.members[0].id, 'bob-slot');
  const bob = await call('/auth/signup', 'POST', { name: 'Bob', email: 'bob@example.com', password: 'test-password-456' });
  const joined = await call('/join', 'POST', { code, memberId: 'bob-slot' }, bob.cookie);
  assert.equal(joined.status, 200);
  assert.equal(joined.body.house.members.length, 2);
  assert.equal(joined.body.house.members[1].userId, bob.body.user.id);
  assert.equal((await call('/household', 'GET', undefined, bob.cookie)).body.house.id, created.body.house.id);
  assert.equal((await call('/rebalance', 'POST', {}, bob.cookie)).status, 403);
  const first = created.body.house.chores[0];
  const completed = await call(`/chores/${first.id}/complete`, 'POST', {}, alice.cookie);
  assert.equal(completed.status, 200);
  const updated = completed.body.house.chores.find(chore => chore.id === first.id);
  assert.notEqual(updated.memberId, first.memberId);
  assert.ok(updated.dueDate > first.dueDate);
  assert.equal(completed.body.house.history.length, 1);
  const undone = await call(`/chores/${first.id}/undo`, 'POST', { completionId: completed.body.completionId }, bob.cookie);
  assert.equal(undone.body.house.chores.find(chore => chore.id === first.id).memberId, first.memberId);
  assert.equal(undone.body.house.history.length, 0);
  assert.equal((await call(`/chores/${first.id}`, 'PATCH', { frequencyDays: 0 }, alice.cookie)).status, 400);
  const edited = await call(`/chores/${first.id}`, 'PATCH', { frequencyDays: 4, memberId: 'bob-slot', dueDate: '2027-01-15' }, bob.cookie);
  assert.equal(edited.body.house.chores.find(chore => chore.id === first.id).frequencyDays, 4);
  const grocery = await call('/groceries', 'POST', { name: 'Strawberries', quantity: '2 punnets' }, bob.cookie);
  assert.equal(grocery.status, 200);
  const groceryId = grocery.body.house.groceries[0].id;
  const checked = await call(`/groceries/${groceryId}`, 'PATCH', { purchased: true }, alice.cookie);
  assert.equal(checked.body.house.groceries[0].purchased, true);
  assert.equal((await call('/household', 'GET', undefined, bob.cookie)).body.house.groceries[0].purchased, true);
  const outsider = await call('/auth/signup', 'POST', { name: 'Charlie', email: 'charlie@example.com', password: 'test-password-789' });
  assert.equal((await call(`/chores/${first.id}`, 'DELETE', {}, outsider.cookie)).status, 404);
  assert.equal((await call('/households', 'POST', { ...payload, name: 'Other house' }, outsider.cookie)).status, 201);
  assert.equal((await call(`/chores/${first.id}`, 'DELETE', {}, outsider.cookie)).status, 404);
  assert.equal((await call('/groceries', 'POST', { name: 'CSRF attempt' }, alice.cookie, { Origin: 'https://evil.example' })).status, 403);
  const content = fs.readFileSync(dataFile, 'utf8');
  assert.ok(!content.includes('test-password-123'));
  assert.ok(!content.includes(alice.cookie.split('=')[1]));
  await new Promise(resolve => server.close(resolve));
  server = createApp({ dataFile, buildDir: folder });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  origin = `http://127.0.0.1:${server.address().port}`;
  const restored = await call('/household', 'GET', undefined, alice.cookie);
  assert.equal(restored.status, 200);
  assert.equal(restored.body.house.groceries[0].name, 'Strawberries');
  assert.equal((await call('/auth/logout', 'POST', {}, alice.cookie)).status, 200);
  assert.equal((await call('/household', 'GET', undefined, alice.cookie)).status, 401);
});
